USE ecommerce_clickstream;

-- Q1. JOIN 3 bang: danh sach san pham + danh muc + thuong hieu.
SELECT p.product_id, p.sku, p.product_name,
       c.category_name, b.brand_name,
       p.price, p.stock_quantity, p.status
FROM products AS p
JOIN categories AS c ON c.category_id = p.category_id
JOIN brands AS b ON b.brand_id = p.brand_id
ORDER BY c.category_name, p.product_name;

-- Q2. JOIN 4 bang: chi tiet don hang va thong tin khach hang.
SELECT o.order_id, o.order_date, o.order_status,
       cu.full_name, p.product_name,
       oi.quantity, oi.unit_price, oi.discount_amount,
       (oi.quantity * oi.unit_price - oi.discount_amount) AS line_total
FROM orders AS o
JOIN customers AS cu ON cu.customer_id = o.customer_id
JOIN order_items AS oi ON oi.order_id = o.order_id
JOIN products AS p ON p.product_id = oi.product_id
WHERE o.order_id = '1001'
ORDER BY oi.order_item_id;

-- Q3. THONG KE: doanh thu va so luong ban theo danh muc.
SELECT c.category_id, c.category_name,
       SUM(oi.quantity) AS units_sold,
       SUM(oi.quantity * oi.unit_price - oi.discount_amount) AS revenue
FROM categories AS c
JOIN products AS p ON p.category_id = c.category_id
JOIN order_items AS oi ON oi.product_id = p.product_id
JOIN orders AS o ON o.order_id = oi.order_id
WHERE o.order_status = 'COMPLETED'
GROUP BY c.category_id, c.category_name
ORDER BY revenue DESC;

-- Q4. Thong ke san pham ban chay theo so luong.
SELECT p.product_id, p.sku, p.product_name,
       SUM(oi.quantity) AS total_quantity_sold,
       SUM(oi.quantity * oi.unit_price - oi.discount_amount) AS revenue
FROM products AS p
JOIN order_items AS oi ON oi.product_id = p.product_id
JOIN orders AS o ON o.order_id = oi.order_id
WHERE o.order_status = 'COMPLETED'
GROUP BY p.product_id, p.sku, p.product_name
ORDER BY total_quantity_sold DESC, revenue DESC
LIMIT 20;

-- Q5. Thong ke thanh toan theo trang thai va phuong thuc.
SELECT payment_method, payment_status,
       COUNT(*) AS payment_count,
       SUM(amount) AS total_amount
FROM payments
GROUP BY payment_method, payment_status
ORDER BY payment_method, payment_status;

-- Q6. Tim san pham sap het hang theo danh muc va thuong hieu.
SELECT p.product_id, p.sku, p.product_name,
       c.category_name, b.brand_name, p.stock_quantity
FROM products p
JOIN categories c ON c.category_id = p.category_id
JOIN brands b ON b.brand_id = p.brand_id
WHERE p.stock_quantity <= 15 AND p.status = 'ACTIVE'
ORDER BY p.stock_quantity ASC;
