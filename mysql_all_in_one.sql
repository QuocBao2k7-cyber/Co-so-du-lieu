DROP DATABASE IF EXISTS ecommerce_clickstream;
CREATE DATABASE ecommerce_clickstream CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE ecommerce_clickstream;

CREATE TABLE categories (
  category_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  parent_category_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NULL,
  category_name VARCHAR(120) NOT NULL,
  slug VARCHAR(150) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  CONSTRAINT fk_categories_parent FOREIGN KEY (parent_category_id)
    REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE brands (
  brand_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  brand_name VARCHAR(120) NOT NULL UNIQUE,
  origin_country VARCHAR(80) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
) ENGINE=InnoDB;

-- Gia san pham, tong tien, don gia va giam gia duoc luu bang INT (VND nguyen).
CREATE TABLE products (
  product_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  category_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  brand_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sku VARCHAR(50) NOT NULL UNIQUE,
  product_name VARCHAR(180) NOT NULL,
  description TEXT NULL,
  price INT NOT NULL,
  stock_quantity INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_products_price CHECK (price >= 0),
  CONSTRAINT fk_products_category FOREIGN KEY(category_id) REFERENCES categories(category_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_products_brand FOREIGN KEY(brand_id) REFERENCES brands(brand_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  INDEX idx_products_category(category_id), INDEX idx_products_brand(brand_id),
  INDEX idx_products_status_price(status, price)
) ENGINE=InnoDB;

CREATE TABLE customers (
  customer_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  phone VARCHAR(25) NULL,
  created_at DATETIME NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
) ENGINE=InnoDB;

CREATE TABLE orders (
  order_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  customer_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_date DATETIME NOT NULL,
  order_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  shipping_address VARCHAR(255) NOT NULL,
  total_amount INT NOT NULL DEFAULT 0,
  CONSTRAINT chk_orders_total CHECK(total_amount >= 0),
  CONSTRAINT fk_orders_customer FOREIGN KEY(customer_id) REFERENCES customers(customer_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  INDEX idx_orders_customer_date(customer_id, order_date),
  INDEX idx_orders_status_date(order_status, order_date)
) ENGINE=InnoDB;

CREATE TABLE order_items (
  order_item_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  order_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  quantity INT NOT NULL,
  unit_price INT NOT NULL,
  discount_amount INT NOT NULL DEFAULT 0,
  CONSTRAINT chk_order_items_quantity CHECK(quantity > 0),
  CONSTRAINT chk_order_items_price CHECK(unit_price >= 0),
  CONSTRAINT chk_order_items_discount CHECK(discount_amount >= 0),
  CONSTRAINT fk_order_items_order FOREIGN KEY(order_id) REFERENCES orders(order_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_order_items_product FOREIGN KEY(product_id) REFERENCES products(product_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT uq_order_product UNIQUE(order_id, product_id),
  INDEX idx_order_items_product(product_id)
) ENGINE=InnoDB;

CREATE TABLE payments (
  payment_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  order_id VARCHAR(500) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payment_method VARCHAR(30) NOT NULL,
  amount INT NOT NULL,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  transaction_code VARCHAR(100) NULL UNIQUE,
  paid_at DATETIME NULL,
  CONSTRAINT chk_payments_amount CHECK(amount >= 0),
  CONSTRAINT fk_payments_order FOREIGN KEY(order_id) REFERENCES orders(order_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  INDEX idx_payments_order_status(order_id, payment_status)
) ENGINE=InnoDB;
